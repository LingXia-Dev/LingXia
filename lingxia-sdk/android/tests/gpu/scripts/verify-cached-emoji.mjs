import {execFileSync} from 'node:child_process';
import {mkdirSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const [adb,serial]=process.argv.slice(2),pkg='com.lingxia.example.gpu.dev';
const run=(...a)=>execFileSync(adb,['-s',serial,...a],{timeout:60000});
const shell=(...a)=>run('shell',...a).toString();
const delay=ms=>new Promise(r=>setTimeout(r,ms));
shell('am','force-stop',pkg);shell('am','start','-n',`${pkg}/com.lingxia.example.gpu.MainActivity`);await delay(1800);
shell('uiautomator','dump','/sdcard/cache-emoji.xml');
const xml=shell('cat','/sdcard/cache-emoji.xml');
const node=xml.match(new RegExp(`<node[^>]*resource-id="${pkg}:id/greeting-input"[^>]*>`))?.[0];assert.ok(node);
const [x,y,r,b]=node.match(/bounds="\[(\d+),(\d+)\]\[(\d+),(\d+)\]"/).slice(1).map(Number);
shell('input','tap',String((x+r)/2),String((y+b)/2));await delay(800);
const out='target/gpu-scene-cache-emoji-evidence';mkdirSync(out,{recursive:true});
const result=shell('CLASSPATH=/data/local/tmp/gpu-cache-emoji-probe.jar app_process /system/bin GpuCacheEmojiProbe');
console.log(result);writeFileSync(`${out}/probe.log`,result);
for(let variant=0;variant<2;variant++)for(let phase=0;phase<6;phase++)run('pull',`/data/local/tmp/gpu-cache-emoji-${variant}-${phase}.png`,`${out}/${variant}-${phase}.png`);
const pid=shell('pidof',pkg).trim(),log=run('logcat','-d',`--pid=${pid}`).toString();writeFileSync(`${out}/device.log`,log);
assert.doesNotMatch(log,/FATAL EXCEPTION|Render failed|GPU image resource failed/);
assert.ok(log.split('\n').filter(l=>l.includes('present generation=')&&l.includes('"sceneCacheHit":true')).length>=4);
console.log('PASS: cached color glyph pixels stay stable through caret phases and update after replacement');
