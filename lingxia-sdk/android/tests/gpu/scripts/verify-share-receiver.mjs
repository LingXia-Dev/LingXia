import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const adb = process.argv[2] ?? process.env.ADB ?? 'adb';
const serial = process.argv[3] ?? process.env.ANDROID_SERIAL;
assert.ok(serial, 'Pass adb and device serial, or set ANDROID_SERIAL.');
const raw = execFileSync(adb, ['-s', serial, 'shell', 'run-as', 'com.lingxia.test.receiver', 'cat', 'files/received.jsonl'], {encoding:'utf8'});
const records = raw.trim().split(/\r?\n/).map(JSON.parse).slice(-3);
assert.equal(records.length, 3);
for (const item of records) assert.equal(item.action, 'android.intent.action.SEND');
assert.equal(records[0].mime, 'text/plain');
assert.equal(records[0].text, 'Plain text share; some receivers reject text-only content.');
assert.equal(records[1].mime, 'text/plain');
const link = new URL(records[1].text);
assert.equal(link.origin, 'https://applink.lingxia.app');
assert.equal(link.pathname, '/lxapp/open');
assert.equal(link.searchParams.get('appId'), 'lingxia-showcase-gpu');
assert.equal(link.searchParams.get('path'), 'pages/share/index.ui.js');
assert.equal(link.searchParams.get('from'), 'share-demo');
assert.match(records[2].mime, /^image\//);
assert.equal(records[2].files.length, 1);
const image = records[2].files[0];
assert.equal(image.width, 1024);assert.equal(image.height, 1024);
assert.ok(image.size > 1000);assert.match(image.sha256, /^[0-9a-f]{64}$/);
assert.ok(image.uri.startsWith('content://com.lingxia.example.gpu.dev.lingxia.documents/'));
writeFileSync('target/ui-share-receiver-payloads.jsonl', records.map(JSON.stringify).join('\n')+'\n');
console.log('PASS receiver payloads: exact text, GPU page link/query, readable and decoded 1024x1024 image');
