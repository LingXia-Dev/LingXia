// Writes docs/format.md from the schema itself: the field tables, the markup guide agents get, and
// one sample document with its markup. `--check` writes nothing and fails on drift.
// Run: node --import ./scripts/ts-resolve.mjs scripts/format-doc.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  BLOCK_FIELDS,
  CHAPTER_FIELDS,
  COLUMN_FIELDS,
  DOC_FIELDS,
  EXTENSION_BLOCK_FIELDS,
  INLINE_FIELDS,
  LIST_ITEM_FIELDS,
  SUBTITLE_FIELDS,
  TABLE_ROW_FIELDS,
} from '../src/schema/fields.ts';
import { exportAiSchema, toAgentView, checkDocument } from '../src/schema/index.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'docs', 'format.md');
const check = process.argv.includes('--check');

const typeNames = {
  id: 'id',
  string: 'string',
  integer: 'integer',
  number: 'number',
  boolean: 'boolean',
  true: '`true`',
  object: 'object',
  numberList: 'number[]',
  integerList: 'integer[]',
  enumList: 'list',
  inlines: 'Inline[]',
  blocks: 'Block[]',
  items: 'ListItem[]',
  columns: 'Column[]',
  rows: 'TableRow[]',
  cells: 'Inline[][]',
  chapters: 'Chapter[]',
  subtitles: 'Subtitle[]',
};

function rule(f) {
  const parts = [];
  if (f.enum) parts.push(f.enum.map(v => `\`${v}\``).join(' · '));
  if (f.min !== undefined) parts.push(`≥ ${f.min}`);
  if (f.positive) parts.push('> 0');
  if (f.nonEmpty) parts.push('not empty');
  if (f.url === 'src') parts.push('media URL');
  if (f.url === 'link') parts.push('URL or `#block-id`');
  if (f.keepEmpty) parts.push('`""` kept');
  return parts.join('; ');
}

function table(fields, { updatable = true } = {}) {
  const head = updatable ? '| Field | Type | Required | Default | Allowed | `update` |\n| --- | --- | --- | --- | --- | --- |' : '| Field | Type | Required | Default | Allowed |\n| --- | --- | --- | --- | --- |';
  const rows = fields.map(f => {
    const cells = [`\`${f.name}\``, typeNames[f.type], f.required ? 'yes' : '', f.default === undefined ? '' : `\`${JSON.stringify(f.default)}\``, rule(f)];
    if (updatable) cells.push(f.structural ? '' : 'yes');
    return `| ${cells.join(' | ')} |`;
  });
  return [head, ...rows].join('\n');
}

const sample = {
  version: 1,
  title: 'Week 3: Limits',
  blocks: [
    { id: 'h-intro', type: 'heading', level: 2, runs: [{ text: 'What a limit is' }] },
    {
      id: 'p-def',
      type: 'paragraph',
      runs: [{ text: 'A limit describes where ' }, { math: 'f(x)' }, { text: ' is heading', bold: true }, { text: ', not where it is.' }],
    },
    {
      id: 'c-note',
      type: 'callout',
      tone: 'tip',
      title: [{ text: 'Remember' }],
      blocks: [{ id: 'p-note', type: 'paragraph', runs: [{ text: 'The function need not be defined at the point.' }] }],
    },
    {
      id: 'l-tasks',
      type: 'list',
      style: 'task',
      items: [
        { id: 'i-read', checked: true, runs: [{ text: 'Read section 3.1' }] },
        { id: 'i-try', runs: [{ text: 'Try the exercises' }] },
      ],
    },
    {
      id: 't-values',
      type: 'table',
      headerRow: true,
      rows: [
        { id: 'r-head', cells: [[{ text: 'x' }], [{ text: 'f(x)' }]] },
        { id: 'r-1', cells: [[{ text: '0.9' }], [{ text: '1.9' }]] },
      ],
    },
    { id: 'img-graph', type: 'image', src: 'https://example.com/graph.png', alt: 'Graph of f near 1', width: 480, height: 360 },
  ],
};

const problems = checkDocument(sample).filter(p => p.severity === 'error');
if (problems.length) {
  console.error('format-doc: the sample document is invalid:', problems);
  process.exit(1);
}

// `id` and `type` are on every block; the intro says so once.
const own = fields => fields.filter(f => f.name !== 'id' && f.name !== 'type');
const blockSections = Object.entries(BLOCK_FIELDS).map(([type, fields]) =>
  own(fields).length ? `### \`${type}\`\n\n${table(own(fields))}` : `### \`${type}\`\n\nNo fields beyond \`id\` and \`type\`.`);

const doc = `<!-- Generated by scripts/format-doc.mjs from src/schema; do not edit. -->
# Jinshu document format

A document is JSON: a \`version\`, optional metadata, and a list of blocks. Every block has a
\`type\` and an \`id\`; list items, table rows, columns and inline atoms have an \`id\` too. Ids
are unique in the document, and edits address content by id. Agents read and write the same document as
Jinshu Markup, an XML subset that converts both ways without loss.

Rules that hold for every field below:

- An optional field equal to its default is left out, and a \`true\`-only flag is left out when off.
- Keys the format does not know are kept as they are, so a document from a newer app survives a
  round trip through an older one.
- A document, custom block or inline atom with a \`version\` newer than this package understands is
  read-only: it renders, and edits to it are refused with problem \`VERSION\`.
- \`update\` sets only the fields marked in the \`update\` column; content changes go through
  \`replace\` or the text operations.

## Document

${table(DOC_FIELDS, { updatable: false })}

## Blocks

${blockSections.join('\n\n')}

### Custom blocks (\`x-<scope>-<name>\`)

Registered with \`defineBlock\`; \`attrs\` is checked against the block's own schema.

${table(own(EXTENSION_BLOCK_FIELDS))}

## Nested records

### ListItem

${table(LIST_ITEM_FIELDS, { updatable: false })}

### TableRow

When the table has \`headerRow\`, \`rows[0]\` is the header.

${table(TABLE_ROW_FIELDS, { updatable: false })}

### Column

${table(COLUMN_FIELDS, { updatable: false })}

### Chapter

${table(CHAPTER_FIELDS, { updatable: false })}

### Subtitle

${table(SUBTITLE_FIELDS, { updatable: false })}

## Inline content

\`runs\`, captions, titles and cells hold a list of inlines. Which kind an inline is follows from the
one key it carries: \`text\`, \`break\`, \`math\` or \`inline\`.

### Text run

Marks are flat keys on the run, never nested.

${table(INLINE_FIELDS.text, { updatable: false })}

### Line break

${table(INLINE_FIELDS.break, { updatable: false })}

### Inline math

${table(INLINE_FIELDS.math, { updatable: false })}

### Inline atom (\`x-<scope>-<name>\`)

Registered with \`defineInline\`.

${table(INLINE_FIELDS.atom, { updatable: false })}

## Markup

This is the guide the agent tools carry:

\`\`\`text
${exportAiSchema().markupGuide}
\`\`\`

## Example

\`\`\`json
${JSON.stringify(sample, null, 2)}
\`\`\`

The same document as markup:

\`\`\`xml
${toAgentView(sample)}
\`\`\`
`;

if (check) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== doc) {
    console.error('docs/format.md is out of date; run npm run generate');
    process.exit(1);
  }
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, doc);
}
