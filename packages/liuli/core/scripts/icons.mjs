// Writes the icon modules from the vendored set: one module per icon (src/Icon/icons/<name>.ts),
// the name list (src/Icon/names.ts) and the default set (src/Icon/set.ts). The source is
// icons/icons.json, which maps each semantic name to a file in icons/lucide/; `isFilled` draws that
// file's shapes solid, as a stop sign is. `--check` writes
// nothing and fails on drift. Run: `node scripts/icons.mjs`.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const core = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const source = JSON.parse(readFileSync(join(core, 'icons/icons.json'), 'utf8'));
const out = join(core, 'src/Icon');
const generated = `Generated by scripts/icons.mjs from icons/${source.set}/ (${source.set} ${source.version}, ${source.license.split(',')[0]}); do not edit.`;
const problems = [];

const n = value => String(Math.round(Number(value) * 1000) / 1000);
const attrs = text => Object.fromEntries([...text.matchAll(/([\w-]+)="([^"]*)"/g)].map(match => [match[1], match[2]]));

/** One SVG shape as path data. */
function pathOf(tag, a) {
  if (tag === 'path') return a.d;
  if (tag === 'line') return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
  if (tag === 'polyline' || tag === 'polygon') {
    const values = a.points.trim().split(/[\s,]+/).map(n);
    const pairs = values.flatMap((value, at) => (at % 2 ? [] : [`${value} ${values[at + 1]}`]));
    return `M${pairs.join('L')}${tag === 'polygon' ? 'z' : ''}`;
  }
  if (tag === 'circle') {
    const [cx, cy, r] = [a.cx, a.cy, a.r].map(Number);
    return `M${n(cx - r)} ${n(cy)}a${n(r)} ${n(r)} 0 1 0 ${n(2 * r)} 0a${n(r)} ${n(r)} 0 1 0 ${n(-2 * r)} 0z`;
  }
  if (tag === 'rect') {
    const [x, y, w, h] = [a.x ?? 0, a.y ?? 0, a.width, a.height].map(Number);
    const rx = Math.min(Number(a.rx ?? a.ry ?? 0), w / 2);
    const ry = Math.min(Number(a.ry ?? a.rx ?? 0), h / 2);
    if (!rx || !ry) return `M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}z`;
    const arc = (dx, dy) => `a${n(rx)} ${n(ry)} 0 0 1 ${n(dx)} ${n(dy)}`;
    return `M${n(x + rx)} ${n(y)}h${n(w - 2 * rx)}${arc(rx, ry)}v${n(h - 2 * ry)}${arc(-rx, ry)}h${n(2 * rx - w)}${arc(-rx, -ry)}v${n(2 * ry - h)}${arc(rx, -ry)}z`;
  }
  return undefined;
}

const number = /^[\s,]*(-?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?)/i;
/** A shape's data made safe to follow another in one path: a leading relative move is from the origin, so it is written absolute. */
function standalone(d) {
  const text = d.trim();
  if (text[0] !== 'm') return text;
  let rest = text.slice(1);
  const point = [];
  for (const _ of [0, 1]) {
    const match = number.exec(rest);
    if (!match) return text;
    point.push(match[1]);
    rest = rest.slice(match[0].length);
  }
  // Pairs after a relative move are relative lines.
  return number.test(rest) ? `M${point.join(' ')}l${rest.replace(/^[\s,]+/, '')}` : `M${point.join(' ')}${rest}`;
}

const camel = name => name.replace(/-([a-z0-9])/g, (_, letter) => letter.toUpperCase());
const outputs = new Map();
const names = Object.keys(source.icons);
for (const [name, entry] of Object.entries(source.icons)) {
  if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(name)) problems.push(`icons.json: ${name}: names are lower-case words joined by hyphens`);
  const file = join(core, 'icons', source.set, `${entry.lucide}.svg`);
  if (!existsSync(file)) { problems.push(`icons.json: ${name}: icons/${source.set}/${entry.lucide}.svg is missing`); continue; }
  const svg = readFileSync(file, 'utf8');
  if (!/viewBox="0 0 24 24"/.test(svg)) problems.push(`${entry.lucide}.svg: the grid is not 0 0 24 24`);
  // One path per paint, the shapes joined in it: an ink with alpha is then laid once, so where two strokes cross is no darker.
  const stroked = [];
  const filled = [];
  for (const [, tag, text] of svg.matchAll(/<(path|line|circle|rect|polyline|polygon|ellipse)\s([^>]*?)\/?>/g)) {
    const a = attrs(text);
    const d = pathOf(tag, a);
    if (!d) { problems.push(`${entry.lucide}.svg: <${tag}> is not converted; add it to scripts/icons.mjs`); continue; }
    // A shape with its own fill is a solid mark (a dot); the rest take the icon's stroke.
    (entry.isFilled || (a.fill && a.fill !== 'none') ? filled : stroked).push(standalone(d));
  }
  const paths = [];
  if (stroked.length) paths.push(`'${stroked.join('')}'`);
  if (filled.length) paths.push(`{ d: '${filled.join('')}', fill: 'currentColor' }`);
  if (!paths.length) problems.push(`${entry.lucide}.svg: no shapes`);
  outputs.set(join(out, 'icons', `${name}.ts`), [
    `// ${generated}`,
    "import type { IconDefinition } from '../definition';",
    '',
    `export const ${camel(name)}Icon: IconDefinition = { paths: [${paths.join(', ')}]${entry.isMirrored ? ', isMirrored: true' : ''} };`,
    '',
  ].join('\n'));
}
// The files are one version of the set; the note beside them and the map must name the same one.
const note = join(core, 'icons', source.set, 'README.md');
const noted = existsSync(note) ? /(\d+\.\d+\.\d+)/.exec(readFileSync(note, 'utf8'))?.[1] : undefined;
if (noted !== source.version) problems.push(`icons/${source.set}/README.md names version ${noted ?? 'none'}, icons.json ${source.version}; a set is one version`);
if (!existsSync(join(core, 'icons', source.set, 'LICENSE'))) problems.push(`icons/${source.set}/LICENSE is missing`);
// A vendored file no name uses is dead weight in the package.
for (const file of readdirSync(join(core, 'icons', source.set)).filter(each => each.endsWith('.svg')))
  if (!Object.values(source.icons).some(entry => `${entry.lucide}.svg` === file)) problems.push(`icons/${source.set}/${file}: no name in icons.json uses it`);

outputs.set(join(out, 'names.ts'), [
  `// ${generated}`,
  '',
  '/** The names every icon set answers to. */',
  `export const iconNames = [\n${names.map(name => `  '${name}',`).join('\n')}\n] as const;`,
  '',
  'export type IconName = (typeof iconNames)[number];',
  '',
].join('\n'));
outputs.set(join(out, 'set.ts'), [
  `// ${generated}`,
  "import type { IconSet } from './definition';",
  ...names.map(name => `import { ${camel(name)}Icon } from './icons/${name}';`),
  '',
  `/** The default set: ${names.length} icons from ${source.set[0].toUpperCase()}${source.set.slice(1)}. */`,
  `export const ${source.set}: IconSet = {\n${names.map(name => `  '${name}': ${camel(name)}Icon,`).join('\n')}\n};`,
  '',
].join('\n'));

if (problems.length) { for (const problem of problems) console.log(problem); process.exit(1); }
const stale = [];
for (const [path, contents] of outputs) {
  if (existsSync(path) && readFileSync(path, 'utf8') === contents) continue;
  stale.push(relative(core, path));
  if (!check) { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, contents); }
}
// A module left behind by a removed name.
for (const file of existsSync(join(out, 'icons')) ? readdirSync(join(out, 'icons')) : [])
  if (!outputs.has(join(out, 'icons', file))) { console.log(`src/Icon/icons/${file}: no name in icons.json; delete it`); process.exitCode = 1; }
if (check && stale.length) { console.log(`out of date; run node scripts/icons.mjs:\n${stale.map(path => `  ${path}`).join('\n')}`); process.exit(1); }
console.log(check ? 'liuli icons: up to date' : stale.length ? `wrote ${stale.length} file${stale.length === 1 ? '' : 's'}` : 'liuli icons: up to date');
