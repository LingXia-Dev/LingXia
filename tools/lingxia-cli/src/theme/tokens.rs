//! `lingxia theme tokens`: a theme's numeric scales as Tailwind tokens, for Web pages and editor
//! completion. GPU pages resolve the steps on the device; colours stay roles everywhere.

use anyhow::{Context, Result, bail};
use clap::Args;
use lingxia_theme::Pack;
use serde::Deserialize;
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use super::{THEME_PATH, load};

#[derive(Args, Debug, Clone)]
pub struct TokensConfig {
    /// The theme file (default: `theme.json`, else the built-in theme)
    #[arg(long)]
    pub theme: Option<PathBuf>,
    /// A design system's names map (`{"type", "radius", "controlHeight"}`), written as aliases of the steps
    #[arg(long)]
    pub names: Option<PathBuf>,
    /// The stylesheet to write
    #[arg(short, long, default_value = "theme/tokens.css")]
    pub out: PathBuf,
    /// Fail when the stylesheet is stale instead of writing it
    #[arg(long)]
    pub check: bool,
}

/// A design system's own names for steps: a type name → type step, a radius name → radius
/// step, a control size → spacing units.
#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields, rename_all = "camelCase")]
pub struct Names {
    #[serde(default, rename = "type")]
    pub typography: BTreeMap<String, String>,
    #[serde(default)]
    pub radius: BTreeMap<String, String>,
    #[serde(default)]
    pub control_height: BTreeMap<String, f32>,
}

pub fn run(config: TokensConfig) -> Result<()> {
    let path = config
        .theme
        .clone()
        .or_else(|| Path::new(THEME_PATH).exists().then(|| THEME_PATH.into()));
    let pack = load(path.as_deref())?;
    let names = config.names.as_deref().map(load_names).transpose()?;
    let css = stylesheet(&pack, names.as_ref())?;
    if config.check {
        let current = fs::read_to_string(&config.out).unwrap_or_default();
        if current.replace("\r\n", "\n") != css {
            bail!(
                "{} is stale; run `lingxia theme tokens`",
                config.out.display()
            );
        }
        return Ok(());
    }
    if let Some(parent) = config.out.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent)?;
    }
    fs::write(&config.out, css).with_context(|| format!("write {}", config.out.display()))?;
    println!("Wrote {} from {}", config.out.display(), pack.name);
    Ok(())
}

pub fn load_names(path: &Path) -> Result<Names> {
    let text = fs::read_to_string(path).with_context(|| format!("read {}", path.display()))?;
    serde_json::from_str(&text).with_context(|| format!("{} is not a names map", path.display()))
}

fn px(value: f32) -> String {
    format!("{}px", value)
}

pub fn stylesheet(pack: &Pack, names: Option<&Names>) -> Result<String> {
    let mut lines = vec![
        format!(
            "/* Generated by `lingxia theme tokens` from the {} theme; do not edit. */",
            pack.name
        ),
        "@theme {".to_string(),
        format!("  --spacing: {};", px(pack.space.unit)),
    ];
    for (step, size) in &pack.typography.scale {
        lines.push(format!("  --text-{step}: {};", px(*size)));
        if let Some(leading) = pack.typography.leading.get(step) {
            lines.push(format!("  --text-{step}--line-height: {};", px(*leading)));
        }
    }
    let radius = |step: &str| match step {
        "DEFAULT" => "--radius".to_string(),
        _ => format!("--radius-{step}"),
    };
    for (step, value) in &pack.shape.radius {
        // `full` is Tailwind's built-in pill.
        if step != "full" {
            lines.push(format!("  {}: {};", radius(step), px(*value)));
        }
    }
    // A design system's names point at the steps, so they follow the theme wherever it resolves.
    if let Some(names) = names {
        let mut unknown = Vec::new();
        for (name, step) in &names.typography {
            if !pack.typography.scale.contains_key(step) {
                unknown.push(format!("type.{name}: no type step {step}"));
                continue;
            }
            lines.push(format!("  --text-{name}: var(--text-{step});"));
            lines.push(format!(
                "  --text-{name}--line-height: var(--text-{step}--line-height);"
            ));
        }
        for (name, step) in &names.radius {
            if !pack.shape.radius.contains_key(step) {
                unknown.push(format!("radius.{name}: no radius step {step}"));
                continue;
            }
            lines.push(format!("  --radius-{name}: var({});", radius(step)));
        }
        for (size, units) in &names.control_height {
            lines.push(format!(
                "  --spacing-control-{size}: calc(var(--spacing) * {units});"
            ));
        }
        if !unknown.is_empty() {
            bail!(
                "the names map names steps the theme lacks:\n  {}",
                unknown.join("\n  ")
            );
        }
    }
    // `duration-fast`, `ease-enter` and `ease-spring` in a page are these.
    let motion = &pack.motion;
    for (step, duration) in [
        ("fast", motion.fast),
        ("base", motion.base),
        ("slow", motion.slow),
    ] {
        lines.push(format!("  --transition-duration-{step}: {duration}ms;"));
    }
    for (name, easing) in [
        ("standard", &motion.easing),
        ("enter", &motion.enter),
        ("exit", &motion.exit),
    ] {
        lines.push(format!("  --ease-{name}: {easing};"));
    }
    lines.push(format!("  --ease-spring: spring({});", motion.spring));
    lines.push("}".into());
    Ok(lines.join("\n") + "\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn liuli_names() -> Names {
        load_names(
            &Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("../../packages/liuli/core/tokens.names.json"),
        )
        .unwrap()
    }

    #[test]
    fn the_default_theme_writes_scales_and_no_colours() {
        let css = stylesheet(&load(None).unwrap(), None).unwrap();
        assert!(css.contains("  --text-sm: 13px;\n  --text-sm--line-height: 18px;"));
        assert!(css.contains("  --radius: 8px;") && css.contains("  --radius-lg: 10px;"));
        assert!(!css.contains("--color") && !css.contains("--radius-full"));
        assert!(!css.contains("--radius-control") && !css.contains("--spacing-control"));
        assert!(css.contains(
            "  --transition-duration-fast: 150ms;\n  --transition-duration-base: 200ms;\n  --transition-duration-slow: 300ms;\n  --ease-standard: cubic-bezier(0, 0, 0.2, 1);\n  --ease-enter: cubic-bezier(0, 0, 0.2, 1);\n  --ease-exit: cubic-bezier(0.4, 0, 1, 1);\n  --ease-spring: spring(0);\n}"
        ));
    }

    #[test]
    fn a_names_map_writes_aliases_of_the_steps_never_lengths() {
        let css = stylesheet(&load(None).unwrap(), Some(&liuli_names())).unwrap();
        for line in [
            "  --text-footnote: var(--text-sm);\n  --text-footnote--line-height: var(--text-sm--line-height);",
            "  --text-display: var(--text-3xl);",
            "  --radius-control: var(--radius-lg);",
            "  --radius-dialog: var(--radius-2xl);",
            "  --spacing-control-sm: calc(var(--spacing) * 8);",
            "  --spacing-control-md: calc(var(--spacing) * 10);",
            "  --spacing-control-lg: calc(var(--spacing) * 12);",
        ] {
            assert!(css.contains(line), "{line} in\n{css}");
        }
    }

    #[test]
    fn a_name_for_a_step_the_theme_lacks_fails() {
        let mut pack = lingxia_theme::default_pack();
        pack.typography.scale.remove("xs");
        let error = stylesheet(&pack, Some(&liuli_names()))
            .unwrap_err()
            .to_string();
        assert!(error.contains("type.caption: no type step xs"), "{error}");
    }

    #[test]
    fn the_gpu_showcase_tokens_are_current() {
        let lxapp =
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../../examples/lingxia-showcase/lxapp");
        assert_eq!(
            fs::read_to_string(lxapp.join("theme/tokens.css")).unwrap(),
            stylesheet(
                &load(Some(&lxapp.join(THEME_PATH))).unwrap(),
                Some(&liuli_names())
            )
            .unwrap(),
            "run `lingxia theme tokens --names ../../../packages/liuli/core/tokens.names.json` in the showcase lxapp"
        );
    }
}
