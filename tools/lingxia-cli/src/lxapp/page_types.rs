//! The project's page registry, generated as TypeScript.
//!
//! `@lingxia/types` ships empty `LxAppPages` / `LxAppTabs` / `LxAppPageTypes`,
//! so page names are plain `string` until these files exist. Writing them
//! merges the project's own names in, and every navigation call narrows to
//! them.
//!
//! - `.lingxia/types/pages.generated.d.ts`: page and tab names, for Logic and View.
//! - `.lingxia/logic-types/pages.generated.d.ts`: each page's `definePage`
//!   type, which `lx.nav` and a View's `<link to>` read params and result from.
//! - `.lingxia/types/<page directory>/$types.ts`, per GPU page: the tsconfig's
//!   `rootDirs` lays it beside the page, so `import type { View } from './$types'`
//!   types the View from the page's Logic.
//! - `.lingxia/tsconfig.logic.json` / `.lingxia/tsconfig.view.json`, for a GPU
//!   lxapp: the bases the project's own tsconfig files extend.

use crate::lxapp::framework::{is_gpu_page, page_base};
use crate::lxapp::project::Project;
use crate::lxapp::view::page_logic_path;
use anyhow::{Context, Result, bail};
use serde_json::Value;
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

// Not a `.d.ts`: `skipLibCheck` would hide an unbuilt Logic reference and leave every type `unknown`.
const VIEW_TYPES_FILE: &str = "$types.ts";

const HEADER: &str = "// Generated by the lingxia CLI from this project's manifest. Do not edit.\n\
                      // Regenerated on every build; `.lingxia/` is not checked in.\n";

pub fn generate(project: &Project) -> Result<()> {
    let tabs = tab_names(&project.root)?;
    // `@lingxia/page-types/*` maps to this directory and `pages` is a valid
    // page name, so the filename carries a dot the alias can never resolve.
    write_if_changed(
        &project.root.join(".lingxia/types/pages.generated.d.ts"),
        &render_names(&project.page_names, &tabs),
    )?;
    let mut logic_pages = Vec::new();
    let mut view_types = BTreeMap::new();
    for (name, page_path) in project.page_names.iter().zip(&project.pages) {
        let logic = page_logic_path(project, page_path)?
            .filter(|logic| logic.extension().is_some_and(|ext| ext == "ts"))
            .map(|logic| {
                let relative = logic
                    .strip_prefix(&project.root)
                    .unwrap_or(&logic)
                    .with_extension("");
                relative.to_string_lossy().replace('\\', "/")
            });
        if let Some(specifier) = &logic {
            logic_pages.push((name.clone(), format!("../../{specifier}")));
        }
        if is_gpu_page(&project.root, page_path) {
            let dir = Path::new(page_path)
                .parent()
                .unwrap_or_else(|| Path::new(""))
                .to_path_buf();
            if view_types.contains_key(&dir) {
                bail!(
                    "{page_path}: another page shares its directory; `./$types` types one page per directory"
                );
            }
            let types = render_view_types(&dir, logic.as_deref());
            view_types.insert(dir, types);
        }
    }
    write_if_changed(
        &project
            .root
            .join(".lingxia/logic-types/pages.generated.d.ts"),
        &render_types(&logic_pages),
    )?;
    let gpu = !view_types.is_empty();
    write_view_types(&project.root.join(".lingxia/types"), &view_types)?;
    if gpu {
        write_if_changed(&project.root.join(LOGIC_BASE), &render_logic_base())?;
        write_if_changed(&project.root.join(VIEW_BASE), &render_view_base())?;
        write_if_changed(&project.root.join(GEN_MARKER), HEADER)?;
        check_view_tsconfig(&project.root, &project.pages)?;
    }
    Ok(())
}

pub(crate) const LOGIC_BASE: &str = ".lingxia/tsconfig.logic.json";
const VIEW_BASE: &str = ".lingxia/tsconfig.view.json";
/// Listed in the project's tsconfig `files`, so a `tsc -b` before generation names the fix.
/// The emit options stay in the project's own files: a missing base must not emit JS beside the sources.
const GEN_MARKER: &str = ".lingxia/run-lingxia-gen-types.d.ts";

fn json_header() -> String {
    HEADER.replace(
        "// Regenerated",
        "// Extend it from the project's tsconfig; regenerated",
    )
}

/// The project's file makes Logic emit only declarations, so a View that references it reads its
/// pages' types without their bodies: Logic globals (timers, `fetch`, `App`)
/// never enter the View program.
fn render_logic_base() -> String {
    json_header()
        + r#"{
  "compilerOptions": {
    "target": "ES2020",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "lib": ["ES2020"],
    "types": ["@lingxia/types", "@lingxia/types/logic-globals"],
    "strict": true,
    "esModuleInterop": true,
    "skipLibCheck": true,
    "forceConsistentCasingInFileNames": true,
    "resolveJsonModule": true,
    "isolatedModules": true,
    "allowSyntheticDefaultImports": true,
    "paths": { "@lingxia/page-types/*": ["./types/*"] }
  },
  "include": [
    "../lxapp.ts",
    "../lxapp.config.ts",
    "../pages/**/*.ts",
    "../shared/**/*.ts",
    "../mocks/**/*.ts",
    "./types/**/*.d.ts",
    "./logic-types/**/*.d.ts"
  ],
  "exclude": ["../node_modules", "../dist", "../pages/**/entry.ts"]
}
"#
}

/// The View has no DOM and no Logic globals; `rootDirs` lays `./$types` beside each page.
fn render_view_base() -> String {
    json_header()
        + r#"{
  "compilerOptions": {
    "target": "ES2020",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "lib": ["ES2020"],
    "types": [],
    "jsx": "preserve",
    "strict": true,
    "skipLibCheck": true,
    "forceConsistentCasingInFileNames": true,
    "resolveJsonModule": true,
    "isolatedModules": true,
    "rootDirs": ["..", "./types"]
  },
  "include": ["../pages/**/*.tsx", "../shared/**/*.tsx", "./types/**/*.d.ts", "./types/**/$types.ts"],
  "exclude": ["../node_modules", "../dist"]
}
"#
}

/// A page that imports `./$types` pulls its Logic into the View program unless
/// the View's tsconfig extends the generated base and references the Logic
/// project; typing then fails on Logic globals, far from the cause.
fn check_view_tsconfig(root: &Path, pages: &[String]) -> Result<()> {
    let importer = pages.iter().find_map(|page| {
        let view = root.join(page_base(page)).with_extension("tsx");
        fs::read_to_string(&view)
            .ok()
            .filter(|source| source.contains("'./$types'") || source.contains("\"./$types\""))
            .map(|_| page.clone())
    });
    let Some(importer) = importer else {
        return Ok(());
    };
    let base = root.join(VIEW_BASE);
    for config in &root_configs(root) {
        if extends_chain_reaches(config, &base, 8) {
            return Ok(());
        }
    }
    bail!(
        "{importer} imports `./$types`, but no tsconfig here extends `{VIEW_BASE}`.\n\
         Copy `tsconfig.view.json` and `tsconfig.logic.json` from a new `lingxia new` GPU project: they extend\n\
         `{VIEW_BASE}` and `{LOGIC_BASE}`, and the View references the Logic. Otherwise the View type-checks the Logic's source."
    )
}

/// Whether a tsconfig at the lxapp root extends the generated Logic base.
pub(crate) fn has_logic_tsconfig(root: &Path) -> bool {
    let base = root.join(LOGIC_BASE);
    root_configs(root)
        .iter()
        .any(|config| extends_chain_reaches(config, &base, 8))
}

fn root_configs(root: &Path) -> Vec<PathBuf> {
    let mut configs: Vec<PathBuf> = fs::read_dir(root)
        .into_iter()
        .flatten()
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| {
            path.file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| name.starts_with("tsconfig") && name.ends_with(".json"))
        })
        .collect();
    configs.sort();
    configs
}

fn extends_chain_reaches(config: &Path, target: &Path, depth: usize) -> bool {
    if depth == 0 {
        return false;
    }
    let Some(extends) = fs::read_to_string(config)
        .ok()
        .and_then(|source| json5::from_str::<Value>(&source).ok())
        .and_then(|value| value.get("extends").cloned())
    else {
        return false;
    };
    let parents: Vec<String> = match extends {
        Value::String(one) => vec![one],
        Value::Array(many) => many
            .into_iter()
            .filter_map(|v| v.as_str().map(str::to_string))
            .collect(),
        _ => Vec::new(),
    };
    let dir = config.parent().unwrap_or_else(|| Path::new("."));
    parents.into_iter().any(|parent| {
        let path = dir.join(&parent);
        same_file(&path, target) || extends_chain_reaches(&path, target, depth - 1)
    })
}

fn same_file(a: &Path, b: &Path) -> bool {
    match (a.canonicalize(), b.canonicalize()) {
        (Ok(a), Ok(b)) => a == b,
        _ => false,
    }
}

/// Writes each page's `$types.ts` and removes those of pages that are gone.
fn write_view_types(types_root: &Path, pages: &BTreeMap<PathBuf, String>) -> Result<()> {
    let mut stale = Vec::new();
    collect_view_types(types_root, &mut stale);
    for path in stale {
        let dir = path
            .parent()
            .and_then(|dir| dir.strip_prefix(types_root).ok())
            .map(Path::to_path_buf);
        if dir.is_none_or(|dir| !pages.contains_key(&dir)) {
            fs::remove_file(&path).with_context(|| format!("remove {}", path.display()))?;
        }
    }
    for (dir, types) in pages {
        write_if_changed(&types_root.join(dir).join(VIEW_TYPES_FILE), types)?;
    }
    Ok(())
}

fn collect_view_types(dir: &Path, found: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_view_types(&path, found);
        } else if path.file_name().is_some_and(|name| name == VIEW_TYPES_FILE) {
            found.push(path);
        }
    }
}

/// `dir` is the page's directory; `logic` its Logic module, extensionless, both relative to the lxapp.
fn render_view_types(dir: &Path, logic: Option<&str>) -> String {
    let mut out = String::from(HEADER);
    let Some(logic) = logic else {
        out.push_str("import type { View as PageView } from \"@lingxia/view\";\n\n");
        out.push_str("/** This page has no Logic: no data and no actions. */\n");
        out.push_str("export type View = PageView<{}, {}>;\n");
        return out;
    };
    // `.lingxia/types/`, then one step per directory of the page.
    let up = "../".repeat(2 + dir.components().count());
    // Types only: the Logic module imports its `lx`, so no Logic global enters the View program.
    out.push_str("import type { View as PageView } from \"@lingxia/view\";\n");
    out.push_str("import type { MessagesOf, ParamsOf, ResultOf } from \"@lingxia/logic\";\n");
    out.push_str(&format!(
        "import type page from {:?};\n\n",
        format!("{up}{logic}")
    ));
    out.push_str("/** The View's props, typed from this page's Logic. */\n");
    out.push_str("export type View = PageView<typeof page>;\n");
    out.push_str("export type Params = ParamsOf<typeof page>;\n");
    out.push_str("export type Result = ResultOf<typeof page>;\n");
    out.push_str("export type Messages = MessagesOf<typeof page>;\n");
    out
}

fn write_if_changed(path: &Path, next: &str) -> Result<()> {
    // Rewriting an identical file would churn the watcher for no reason.
    if fs::read_to_string(path).is_ok_and(|current| current == next) {
        return Ok(());
    }
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)
            .with_context(|| format!("create page types directory {}", dir.display()))?;
    }
    fs::write(path, next).with_context(|| format!("write {}", path.display()))
}

fn tab_names(root: &Path) -> Result<Vec<String>> {
    let manifest_path = root.join("lxapp.json");
    let Ok(content) = fs::read_to_string(&manifest_path) else {
        return Ok(Vec::new());
    };
    let manifest: Value = serde_json::from_str(&content)
        .with_context(|| format!("parse {}", manifest_path.display()))?;
    Ok(manifest
        .pointer("/tabBar/items")
        .and_then(Value::as_array)
        .map(|items| {
            items
                .iter()
                .filter_map(|item| item.get("page").and_then(Value::as_str))
                .map(str::to_string)
                .collect()
        })
        .unwrap_or_default())
}

fn render_names(page_names: &[String], tabs: &[String]) -> String {
    let mut out = String::from(HEADER);
    render_interface(
        &mut out,
        "LxAppPages",
        page_names.iter().map(|name| (name, "true")),
    );
    render_interface(
        &mut out,
        "LxAppTabs",
        tabs.iter().map(|name| (name, "true")),
    );
    out
}

fn render_types(pages: &[(String, String)]) -> String {
    let mut out = String::from(HEADER);
    let entries: Vec<(String, String)> = pages
        .iter()
        .map(|(name, specifier)| {
            (
                name.clone(),
                format!("typeof import({specifier:?}).default"),
            )
        })
        .collect();
    render_interface(
        &mut out,
        "LxAppPageTypes",
        entries.iter().map(|(name, ty)| (name, ty.as_str())),
    );
    out
}

fn render_interface<'a>(
    out: &mut String,
    name: &str,
    entries: impl Iterator<Item = (&'a String, &'a str)>,
) {
    out.push_str(&format!("\ninterface {name} {{\n"));
    for (key, ty) in entries {
        // A name that is not a bare identifier still has to be a valid key.
        out.push_str(&format!("  {}: {ty};\n", quote_key(key)));
    }
    out.push_str("}\n");
}

fn quote_key(name: &str) -> String {
    let bare = !name.is_empty()
        && !name.starts_with(|c: char| c.is_ascii_digit())
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if bare {
        name.to_string()
    } else {
        format!("{name:?}")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_bare_and_quoted_keys() {
        let rendered = render_names(&["home".into(), "my-page".into(), "2fa".into()], &[]);
        assert!(rendered.contains("  home: true;\n"));
        assert!(rendered.contains("  \"my-page\": true;\n"));
        assert!(rendered.contains("  \"2fa\": true;\n"));
    }

    #[test]
    fn an_lxapp_without_pages_still_declares_the_interfaces() {
        let rendered = render_names(&[], &[]);
        assert!(rendered.contains("interface LxAppPages {\n}\n"));
        assert!(rendered.contains("interface LxAppTabs {\n}\n"));
    }

    #[test]
    fn a_page_view_types_import_its_logic_from_beside_the_page() {
        let rendered = render_view_types(Path::new("pages/order"), Some("pages/order/index"));
        assert!(rendered.contains("import type page from \"../../../../pages/order/index\";\n"));
        assert!(rendered.contains("export type View = PageView<typeof page>;\n"));
        assert!(rendered.contains("export type Params = ParamsOf<typeof page>;\n"));
    }

    #[test]
    fn a_page_without_logic_gets_a_view_with_no_data_or_actions() {
        let rendered = render_view_types(Path::new("pages/about"), None);
        assert!(rendered.contains("export type View = PageView<{}, {}>;\n"));
        assert!(!rendered.contains("import type page"));
    }

    #[test]
    fn view_types_of_a_removed_page_are_deleted() {
        let temp = tempfile::tempdir().unwrap();
        let root = temp.path();
        fs::create_dir_all(root.join("pages/gone")).unwrap();
        fs::write(root.join("pages/gone").join(VIEW_TYPES_FILE), "").unwrap();
        fs::write(root.join("pages.generated.d.ts"), "").unwrap();
        let pages = BTreeMap::from([(PathBuf::from("pages/home"), "next".to_string())]);
        write_view_types(root, &pages).unwrap();
        assert!(!root.join("pages/gone").join(VIEW_TYPES_FILE).exists());
        assert!(root.join("pages.generated.d.ts").exists());
        assert_eq!(
            fs::read_to_string(root.join("pages/home").join(VIEW_TYPES_FILE)).unwrap(),
            "next"
        );
    }

    #[test]
    fn page_types_point_at_each_page_default_export() {
        let rendered = render_types(&[("order".into(), "../../pages/order/index".into())]);
        assert!(
            rendered.contains("  order: typeof import(\"../../pages/order/index\").default;\n")
        );
    }

    fn typed_view_project(view_config: &str) -> tempfile::TempDir {
        let temp = tempfile::tempdir().unwrap();
        let root = temp.path();
        fs::create_dir_all(root.join("pages/home")).unwrap();
        fs::create_dir_all(root.join(".lingxia")).unwrap();
        fs::write(
            root.join("pages/home/index.tsx"),
            "import type { View } from './$types';\n",
        )
        .unwrap();
        fs::write(root.join(VIEW_BASE), render_view_base()).unwrap();
        fs::write(root.join("tsconfig.view.json"), view_config).unwrap();
        temp
    }

    #[test]
    fn a_typed_view_whose_tsconfig_extends_the_base_builds() {
        let temp = typed_view_project(
            "// the View\n{ \"extends\": \"./.lingxia/tsconfig.view.json\", \"references\": [] }",
        );
        check_view_tsconfig(temp.path(), &["pages/home/index".into()]).unwrap();
    }

    #[test]
    fn a_typed_view_whose_tsconfig_skips_the_base_fails_the_build() {
        let temp = typed_view_project(r#"{ "compilerOptions": { "jsx": "preserve" } }"#);
        let error = check_view_tsconfig(temp.path(), &["pages/home/index".into()]).unwrap_err();
        assert!(
            error
                .to_string()
                .contains("extends `.lingxia/tsconfig.view.json`"),
            "{error}"
        );
    }

    #[test]
    fn a_view_typed_by_hand_needs_no_base() {
        let temp = typed_view_project("{}");
        fs::write(
            temp.path().join("pages/home/index.tsx"),
            "export function render() {}\n",
        )
        .unwrap();
        check_view_tsconfig(temp.path(), &["pages/home/index".into()]).unwrap();
    }

    #[test]
    fn the_bases_parse_as_tsconfig() {
        for base in [render_logic_base(), render_view_base()] {
            let config: Value = json5::from_str(&base).unwrap();
            assert!(config["compilerOptions"]["lib"] == serde_json::json!(["ES2020"]));
        }
        assert!(!render_logic_base().contains("emit"));
        assert!(!render_view_base().contains("noEmit"));
        assert!(render_logic_base().contains(r#""../mocks/**/*.ts""#));
        assert!(render_view_base().contains(r#""types": []"#));
    }
}
