//! `lingxia gen tokens`: a theme pack's numeric scales as Tailwind tokens for GPU pages.
//! Colours stay out: pages name roles, and the palette arrives at runtime.

use anyhow::{Context, Result, bail};
use clap::Args;
use lingxia_theme::Pack;
use std::fs;
use std::path::{Path, PathBuf};

/// Where an lxapp keeps its own pack; without one the built-in default applies.
pub const PACK_PATH: &str = "theme/pack.json";

#[derive(Args, Debug, Clone)]
pub struct TokensConfig {
    /// Theme pack JSON. Defaults to `theme/pack.json`, else the built-in pack.
    #[arg(long)]
    pub pack: Option<PathBuf>,
    /// The stylesheet to write.
    #[arg(short, long, default_value = "theme/tokens.css")]
    pub out: PathBuf,
    /// Fail when the stylesheet is stale instead of writing it.
    #[arg(long)]
    pub check: bool,
}

pub fn run(config: TokensConfig) -> Result<()> {
    let path = config
        .pack
        .clone()
        .or_else(|| Path::new(PACK_PATH).exists().then(|| PACK_PATH.into()));
    let pack = load(path.as_deref())?;
    let css = stylesheet(&pack);
    if config.check {
        let current = fs::read_to_string(&config.out).unwrap_or_default();
        if current.replace("\r\n", "\n") != css {
            bail!(
                "{} is stale; run `lingxia gen tokens`",
                config.out.display()
            );
        }
        return Ok(());
    }
    if let Some(parent) = config.out.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent)?;
    }
    fs::write(&config.out, css).with_context(|| format!("write {}", config.out.display()))?;
    println!("Wrote {} from {}", config.out.display(), pack.name);
    Ok(())
}

/// The pack at `path`, or the built-in one; fails listing every contrast or schema problem.
pub fn load(path: Option<&Path>) -> Result<Pack> {
    let pack = match path {
        None => lingxia_theme::default_pack(),
        Some(path) => {
            let text =
                fs::read_to_string(path).with_context(|| format!("read {}", path.display()))?;
            lingxia_theme::complete(
                serde_json::from_str(&text)
                    .with_context(|| format!("{} is not a theme pack", path.display()))?,
            )
        }
    };
    let problems = lingxia_theme::check(&pack);
    if !problems.is_empty() {
        let list: Vec<String> = problems.iter().map(|p| format!("  {p}")).collect();
        bail!(
            "theme pack {} fails its checks:\n{}",
            pack.name,
            list.join("\n")
        );
    }
    for advice in lingxia_theme::advise(&pack) {
        eprintln!("warning: theme pack {}: {advice}", pack.name);
    }
    Ok(pack)
}

fn px(value: f32) -> String {
    format!("{}px", value)
}

/// Liuli's names for type steps: a role in the text, not a size.
const TYPE_NAMES: [(&str, &str); 6] = [
    ("caption", "xs"),
    ("footnote", "sm"),
    ("body", "base"),
    ("callout", "lg"),
    ("title", "xl"),
    ("display", "3xl"),
];
/// Liuli's names for corner radii: what the shape is, not how big.
const RADIUS_NAMES: [(&str, &str); 5] = [
    ("checkbox", "sm"),
    ("segment", "md"),
    ("control", "lg"),
    ("container", "xl"),
    ("dialog", "2xl"),
];
/// Control heights in spacing units.
const CONTROL_HEIGHTS: [(&str, f32); 3] = [("sm", 8.0), ("md", 10.0), ("lg", 12.0)];

pub fn stylesheet(pack: &Pack) -> String {
    let mut lines = vec![
        format!(
            "/* Generated by `lingxia gen tokens` from the {} theme pack; do not edit. */",
            pack.name
        ),
        "@theme {".to_string(),
        format!("  --spacing: {};", px(pack.space.unit)),
    ];
    for (step, size) in &pack.typography.scale {
        lines.push(format!("  --text-{step}: {};", px(*size)));
        if let Some(leading) = pack.typography.leading.get(step) {
            lines.push(format!("  --text-{step}--line-height: {};", px(*leading)));
        }
    }
    for (step, radius) in &pack.shape.radius {
        // `full` is Tailwind's built-in pill; DEFAULT is the bare `rounded`.
        match step.as_str() {
            "full" => continue,
            "DEFAULT" => lines.push(format!("  --radius: {};", px(*radius))),
            _ => lines.push(format!("  --radius-{step}: {};", px(*radius))),
        }
    }
    // The design system's names, so a pack reshapes its components with the same ramps.
    for (name, step) in TYPE_NAMES {
        let Some(size) = pack.typography.scale.get(step) else {
            continue;
        };
        lines.push(format!("  --text-{name}: {};", px(*size)));
        if let Some(leading) = pack.typography.leading.get(step) {
            lines.push(format!("  --text-{name}--line-height: {};", px(*leading)));
        }
    }
    for (name, step) in RADIUS_NAMES {
        if let Some(radius) = pack.shape.radius.get(step) {
            lines.push(format!("  --radius-{name}: {};", px(*radius)));
        }
    }
    for (size, units) in CONTROL_HEIGHTS {
        lines.push(format!(
            "  --spacing-control-{size}: {};",
            px(units * pack.space.unit)
        ));
    }
    // `duration-fast`, `ease-enter` and `ease-spring` in a page are these.
    let motion = &pack.motion;
    for (step, duration) in [
        ("fast", motion.fast),
        ("base", motion.base),
        ("slow", motion.slow),
    ] {
        lines.push(format!("  --transition-duration-{step}: {duration}ms;"));
    }
    for (name, easing) in [
        ("standard", &motion.easing),
        ("enter", &motion.enter),
        ("exit", &motion.exit),
    ] {
        lines.push(format!("  --ease-{name}: {easing};"));
    }
    lines.push(format!("  --ease-spring: spring({});", motion.spring));
    lines.push("}".into());
    lines.join("\n") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_default_pack_writes_scales_and_no_colours() {
        let css = stylesheet(&load(None).unwrap());
        assert!(css.contains("  --text-sm: 13px;\n  --text-sm--line-height: 18px;"));
        assert!(css.contains("  --radius: 8px;") && css.contains("  --radius-lg: 10px;"));
        assert!(!css.contains("--color") && !css.contains("--radius-full"));
        assert!(css.contains(
            "  --transition-duration-fast: 150ms;\n  --transition-duration-base: 200ms;\n  --transition-duration-slow: 300ms;\n  --ease-standard: cubic-bezier(0, 0, 0.2, 1);\n  --ease-enter: cubic-bezier(0, 0, 0.2, 1);\n  --ease-exit: cubic-bezier(0.4, 0, 1, 1);\n  --ease-spring: spring(0);\n}"
        ));
    }

    #[test]
    fn the_design_systems_names_follow_the_packs_ramps() {
        let mut pack = lingxia_theme::default_pack();
        pack.typography.scale.insert("sm".into(), 13.0);
        pack.typography.leading.insert("sm".into(), 18.0);
        pack.typography.scale.insert("3xl".into(), 28.0);
        pack.shape.radius.insert("lg".into(), 10.0);
        pack.shape.radius.insert("2xl".into(), 20.0);
        pack.space.unit = 5.0;
        let css = stylesheet(&pack);
        for line in [
            "  --text-footnote: 13px;\n  --text-footnote--line-height: 18px;",
            "  --text-display: 28px;",
            "  --radius-control: 10px;",
            "  --radius-dialog: 20px;",
            "  --spacing-control-sm: 40px;",
            "  --spacing-control-md: 50px;",
            "  --spacing-control-lg: 60px;",
        ] {
            assert!(css.contains(line), "{line} in\n{css}");
        }
        // A pack without a step leaves its name to the design system's own default.
        pack.typography.scale.remove("xs");
        pack.shape.radius.remove("md");
        let css = stylesheet(&pack);
        assert!(!css.contains("--text-caption") && !css.contains("--radius-segment"));
    }

    #[test]
    fn a_failing_pack_names_each_problem() {
        let dir = std::env::temp_dir().join(format!("lingxia-pack-{}", std::process::id()));
        fs::create_dir_all(&dir).unwrap();
        let mut pack = lingxia_theme::default_pack();
        pack.appearance.light.insert(
            "text-muted".into(),
            lingxia_theme::Rgba::parse("#dddddd").unwrap(),
        );
        let path = dir.join("pack.json");
        fs::write(&path, serde_json::to_string(&pack).unwrap()).unwrap();
        let error = load(Some(&path)).unwrap_err().to_string();
        assert!(error.contains("light: text-muted on surface is"), "{error}");
        fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn the_gpu_showcase_tokens_are_current() {
        let theme = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../examples/lingxia-showcase-gpu/lxapp/theme");
        assert_eq!(
            fs::read_to_string(theme.join("tokens.css")).unwrap(),
            stylesheet(&load(Some(&theme.join("pack.json"))).unwrap()),
            "run `lingxia gen tokens` in the showcase lxapp"
        );
    }
}
