//! `lingxia gen tokens`: a theme pack's numeric scales as Tailwind tokens for GPU pages.
//! Colours stay out: pages name roles, and the palette arrives at runtime.

use anyhow::{Context, Result, bail};
use clap::Args;
use lingxia_theme::Pack;
use std::fs;
use std::path::{Path, PathBuf};

/// Where an lxapp keeps its own pack; without one the built-in default applies.
pub const PACK_PATH: &str = "theme/pack.json";

#[derive(Args, Debug, Clone)]
pub struct TokensConfig {
    /// Theme pack JSON. Defaults to `theme/pack.json`, else the built-in pack.
    #[arg(long)]
    pub pack: Option<PathBuf>,
    /// The stylesheet to write.
    #[arg(short, long, default_value = "theme/tokens.css")]
    pub out: PathBuf,
    /// Fail when the stylesheet is stale instead of writing it.
    #[arg(long)]
    pub check: bool,
}

pub fn run(config: TokensConfig) -> Result<()> {
    let path = config
        .pack
        .clone()
        .or_else(|| Path::new(PACK_PATH).exists().then(|| PACK_PATH.into()));
    let pack = load(path.as_deref())?;
    let css = stylesheet(&pack);
    if config.check {
        let current = fs::read_to_string(&config.out).unwrap_or_default();
        if current.replace("\r\n", "\n") != css {
            bail!(
                "{} is stale; run `lingxia gen tokens`",
                config.out.display()
            );
        }
        return Ok(());
    }
    if let Some(parent) = config.out.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent)?;
    }
    fs::write(&config.out, css).with_context(|| format!("write {}", config.out.display()))?;
    println!("Wrote {} from {}", config.out.display(), pack.name);
    Ok(())
}

/// The pack at `path`, or the built-in one; fails listing every contrast or schema problem.
pub fn load(path: Option<&Path>) -> Result<Pack> {
    let pack = match path {
        None => lingxia_theme::default_pack(),
        Some(path) => {
            let text =
                fs::read_to_string(path).with_context(|| format!("read {}", path.display()))?;
            lingxia_theme::complete(
                serde_json::from_str(&text)
                    .with_context(|| format!("{} is not a theme pack", path.display()))?,
            )
        }
    };
    let problems = lingxia_theme::check(&pack);
    if !problems.is_empty() {
        let list: Vec<String> = problems.iter().map(|p| format!("  {p}")).collect();
        bail!(
            "theme pack {} fails its checks:\n{}",
            pack.name,
            list.join("\n")
        );
    }
    Ok(pack)
}

fn px(value: f32) -> String {
    format!("{}px", value)
}

pub fn stylesheet(pack: &Pack) -> String {
    let mut lines = vec![
        format!(
            "/* Generated by `lingxia gen tokens` from the {} theme pack; do not edit. */",
            pack.name
        ),
        "@theme {".to_string(),
        format!("  --spacing: {};", px(pack.space.unit)),
    ];
    for (step, size) in &pack.typography.scale {
        lines.push(format!("  --text-{step}: {};", px(*size)));
        if let Some(leading) = pack.typography.leading.get(step) {
            lines.push(format!("  --text-{step}--line-height: {};", px(*leading)));
        }
    }
    for (step, radius) in &pack.shape.radius {
        // `full` is Tailwind's built-in pill; DEFAULT is the bare `rounded`.
        match step.as_str() {
            "full" => continue,
            "DEFAULT" => lines.push(format!("  --radius: {};", px(*radius))),
            _ => lines.push(format!("  --radius-{step}: {};", px(*radius))),
        }
    }
    lines.push("}".into());
    lines.join("\n") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_default_pack_writes_scales_and_no_colours() {
        let css = stylesheet(&load(None).unwrap());
        assert!(css.contains("  --text-sm: 14px;\n  --text-sm--line-height: 20px;"));
        assert!(css.contains("  --radius: 8px;") && css.contains("  --radius-lg: 12px;"));
        assert!(!css.contains("--color") && !css.contains("--radius-full"));
    }

    #[test]
    fn a_failing_pack_names_each_problem() {
        let dir = std::env::temp_dir().join(format!("lingxia-pack-{}", std::process::id()));
        fs::create_dir_all(&dir).unwrap();
        let mut pack = lingxia_theme::default_pack();
        pack.appearance.light.insert(
            "text-muted".into(),
            lingxia_theme::Rgba::parse("#dddddd").unwrap(),
        );
        let path = dir.join("pack.json");
        fs::write(&path, serde_json::to_string(&pack).unwrap()).unwrap();
        let error = load(Some(&path)).unwrap_err().to_string();
        assert!(error.contains("light: text-muted on surface is"), "{error}");
        fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn the_gpu_showcase_tokens_are_current() {
        let theme = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../examples/lingxia-showcase-gpu/lxapp/theme");
        assert_eq!(
            fs::read_to_string(theme.join("tokens.css")).unwrap(),
            stylesheet(&load(Some(&theme.join("pack.json"))).unwrap()),
            "run `lingxia gen tokens` in the showcase lxapp"
        );
    }
}
